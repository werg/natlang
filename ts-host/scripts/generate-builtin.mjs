#!/usr/bin/env node
/**
 * Embed what natlang ships as text so the same bytes work in the Node build, the npm package, the browser bundle and the
 * workerd core without file access at run time:
 *   - the built-in natlang programs (src/builtin/*.nl) as src/builtin/sources.generated.ts;
 *   - the eval prelude (prelude.js, the crisp standard library of eval code) as src/native/prelude.generated.ts.
 * The `.nl` files and prelude.js are the sources; `--check` fails when a generated module is stale.
 * Usage: node scripts/generate-builtin.mjs [--check]
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const dir = join(root, 'src/builtin');
const names = readdirSync(dir).filter(name => name.endsWith('.nl')).sort();
const generated = [
  { target: join(dir, 'sources.generated.ts'), regenerate: 'the .nl files in this folder', text: `// Generated by scripts/generate-builtin.mjs from the .nl files in this folder. Do not edit; edit the .nl files and run
// \`node scripts/generate-builtin.mjs\` (npm run build:node does).
/** The built-in natlang programs by file name without \`.nl\`: the exact bytes of each file. */
export const BUILTIN_SOURCES: Readonly<Record<string, string>> = {
${names.map(name => `  ${JSON.stringify(name.slice(0, -3))}: ${JSON.stringify(readFileSync(join(dir, name), 'utf8'))},`).join('\n')}
};
` },
  { target: join(root, 'src/native/prelude.generated.ts'), regenerate: 'prelude.js', text: `// Generated by scripts/generate-builtin.mjs from prelude.js. Do not edit; edit prelude.js and run
// \`node scripts/generate-builtin.mjs\` (npm run build:node does).
/** The crisp standard library every eval sees (prelude.js): the exact bytes of the file. */
export const PRELUDE: string = ${JSON.stringify(readFileSync(join(root, 'prelude.js'), 'utf8'))};
` },
];
if (process.argv.includes('--check')) {
  const stale = generated.filter(({ target, text }) => !existsSync(target) || readFileSync(target, 'utf8') !== text);
  for (const { target } of stale) console.error(`${target.slice(root.length + 1)} is stale; run: node scripts/generate-builtin.mjs`);
  if (stale.length) process.exit(1);
} else for (const { target, text } of generated) writeFileSync(target, text);
