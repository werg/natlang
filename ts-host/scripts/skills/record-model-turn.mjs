/** Record the effective runtime turn, retaining every wire attempt as separate evidence. */
export function recordingModelDriver({ createDriver, record, recordWire, recordFailure }) {
  return async (request, signal) => {
    const input = structuredClone(request), wireExchanges = [];
    // A callback belongs to one invocation, including its transport-level retries.
    const driver = createDriver(async exchange => {
      const snapshot = structuredClone(exchange);
      wireExchanges.push(snapshot);
      await recordWire?.(structuredClone(snapshot));
    });
    let turn;
    try { turn = await driver(request, signal); }
    catch (error) {
      await recordFailure?.({ recording_version: 'natlang.model-failure/1', request: input,
        diagnostic: modelFailureDiagnostic(error, signal), wireExchanges });
      throw error;
    }
    await record({ recording_version: 'natlang.effective-model-turn/1', request: input,
      turn: structuredClone(turn), wireExchanges });
    return turn;
  };
}

/** Classify actual thrown transport evidence, never text generated by a model. */
export function modelFailureDiagnostic(error, signal) {
  const causes = [], seen = new Set();
  for (let item = error; item && !seen.has(item) && causes.length < 8; item = item.cause) {
    seen.add(item);
    causes.push({ name: typeof item.name === 'string' ? item.name : typeof item,
      message: String(item.message ?? item).slice(0, 2000),
      ...(typeof item.code === 'string' ? { code: item.code } : {}),
      ...(Number.isInteger(item.status) ? { status: item.status } : {}) });
  }
  const codes = new Set(['UND_ERR_SOCKET', 'UND_ERR_CONNECT_TIMEOUT', 'UND_ERR_HEADERS_TIMEOUT',
    'UND_ERR_BODY_TIMEOUT', 'ECONNRESET', 'ECONNREFUSED', 'EPIPE', 'ETIMEDOUT', 'EAI_AGAIN']);
  return { causes, aborted: !!signal?.aborted,
    retryable: !signal?.aborted && causes.some(item => codes.has(item.code) ||
      [408, 429, 500, 502, 503, 504].includes(item.status)) };
}

/** Preserve absorbed infrastructure failures as separate, non-training attempts. */
export function withModelFailures(result, modelFailures, signal) {
  if (signal?.aborted || !modelFailures.some(row => row.diagnostic.retryable)) return result;
  return { ...result, originalDisposition: result.disposition, originalPositive: result.positive,
    disposition: 'provider_failure', positive: false, retryable: true };
}
