#!/usr/bin/env node
/** Resolve one stable llama.cpp release into natlang's checked runtime manifest. */
import { createHash, randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { cp, mkdir, mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = resolve(dirname(fileURLToPath(import.meta.url)), '..'), repository_root = repository;
const destination = resolve(repository, 'ts-host/src/llama-runtime-release.ts');
const vendor = resolve(repository, 'ts-host/vendor');
const args = process.argv.slice(2), value = name => args.includes(name) ? args[args.indexOf(name) + 1] : undefined;
const requested = value('--version'), forkTag = value('--fork');
if (forkTag ? !/^natlang-b\d+$/.test(forkTag) : !requested || !/^\d+\.\d+\.\d+$/.test(requested))
  throw new Error('usage: node scripts/update_llama_runtime.mjs --version X.Y.Z | --fork natlang-bNNNN [--repository OWNER/REPO] [--wllama BUILT_WLLAMA_DIR]');

const headers = { accept: 'application/vnd.github+json', 'user-agent': 'natlang-runtime-publisher' };
async function getJson(url) {
  const response = await fetch(url, { headers });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
}
async function getText(url) {
  const response = await fetch(url, { headers });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return (await response.text()).trim();
}

async function writeManifest(manifest) {
  const source = `/** Generated by scripts/update_llama_runtime.mjs; do not edit by hand. */
import type { LlamaRuntimeRelease } from './model/llama-runtime.js';

export const LLAMA_RUNTIME_RELEASE = Object.freeze(${JSON.stringify(manifest, null, 2)} satisfies LlamaRuntimeRelease);
`;
  const temporary = `${destination}.${randomUUID()}.tmp`;
  await writeFile(temporary, source);
  await rename(temporary, destination);
  process.stdout.write(JSON.stringify({ version: manifest.version, build: manifest.build, commit: manifest.commit,
    artifacts: manifest.artifacts.map(artifact => artifact.key) }) + '\n');
}

// A release of natlang's llama.cpp fork (its natlang-runtime workflow): the manifest it publishes lists every archive's os,
// arch, backends, role, size and digest, so no API call is needed. natlang runs the CPU build of each platform, and Metal
// where the same archive carries it; the GPU archives of the release are Vibestudio's local-models engine's to select.
if (forkTag) {
  const repository = value('--repository') ?? 'werg/llama.cpp-neuralese';
  const base = `https://github.com/${repository}/releases/download/${forkTag}`;
  const release = JSON.parse(await getText(`${base}/natlang-runtime.json`));
  if (release.schema !== 'natlang.llama-runtime-release/2' || release.tag !== forkTag) throw new Error(`${base}/natlang-runtime.json is not this release's manifest`);
  await requireParityReview(repository, release);
  const servers = release.archives.filter(archive => archive.role === 'server');
  const artifacts = [];
  for (const [platform, arch] of [...new Set(servers.map(archive => `${archive.os} ${archive.arch}`))].map(pair => pair.split(' '))) {
    const candidates = servers.filter(archive => archive.os === platform && archive.arch === arch);
    for (const backend of ['metal', 'cpu']) {
      const row = candidates.find(archive => archive.backends.includes(backend));
      if (!row) continue;
      artifacts.push({ key: `${platform}-${arch}-${backend}`, platform, arch, backend, archive: row.file.endsWith('.zip') ? 'zip' : 'tar.gz',
        url: `${base}/${row.file}`, bytes: row.bytes, sha256: row.sha256 });
      break;
    }
  }
  if (!artifacts.length) throw new Error(`${forkTag} publishes no natlang runtime archives`);
  const [major, minor] = release.version.split('.').map(Number);
  // The in-page engine is the same fork commit compiled to WebAssembly (the release's wllama archive), so the browser
  // never runs older server code than the managed runtime; ts-host/test/llama-runtime.test.mjs checks the pair.
  await installWllama(release, base, repository);
  await writeManifest({ version: release.version, build: release.build, commit: release.commit,
    compatible: { minimumVersion: release.version, maximumVersionExclusive: `${major}.${minor + 1}.0`, minimumBuild: release.build }, artifacts });
  process.exit(0);
}

/**
 * The fork's own commits between the pinned runtime and this release (upstream merges carry a `(#NNNN)` PR suffix) must
 * each be accounted for in docs/ENGINE_PARITY.md: a serving change reaches the Python native engine and the SGLang actor
 * too, or its gap is recorded with a next action.
 */
async function requireParityReview(repository, release) {
  const pinned = /"commit": "([0-9a-f]+)"/.exec(await readFile(destination, 'utf8'))?.[1];
  if (!pinned || release.commit.startsWith(pinned)) return;
  const compare = await getJson(`https://api.github.com/repos/${repository}/compare/${pinned}...${release.commit}`);
  if (compare.status !== 'ahead') throw new Error(`${release.tag} (${release.commit}) does not descend from the pinned ${pinned}`);
  if (compare.total_commits > compare.commits.length) throw new Error(`${compare.total_commits} commits since ${pinned}: review them in smaller pin steps`);
  const parity = await readFile(resolve(repository_root, 'docs/ENGINE_PARITY.md'), 'utf8');
  const own = compare.commits.filter(commit => commit.parents.length === 1 && !/\(#\d+\)\s*$/.test(commit.commit.message.split('\n')[0]));
  const missing = own.filter(commit => !parity.includes(commit.sha.slice(0, 9)));
  if (missing.length) throw new Error(`fork commits not yet reviewed for engine parity; add each to docs/ENGINE_PARITY.md (its gap row, or the reviewed list):\n${
    missing.map(commit => `  ${commit.sha.slice(0, 9)} ${commit.commit.message.split('\n')[0]}`).join('\n')}`);
}

/**
 * Vendor the release's wllama build into ts-host/vendor/wllama{,-compat} and record its provenance. `--wllama DIR`
 * takes a local build of werg/wllama whose llama.cpp submodule is checked out at the release's commit instead.
 */
async function installWllama(release, base, repository) {
  let built = value('--wllama') && resolve(value('--wllama')), wllama, temporary;
  if (built) {
    const commit = execFileSync('git', ['-C', join(built, 'llama.cpp'), 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
    if (!commit.startsWith(release.commit)) throw new Error(`${built}/llama.cpp is at ${commit}, the release is ${release.commit}`);
    wllama = { repository: 'werg/wllama', commit: execFileSync('git', ['-C', built, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(),
      dirty: execFileSync('git', ['-C', built, 'status', '--porcelain', '--', '.', ':!llama.cpp'], { encoding: 'utf8' }).trim() !== '' };
  } else {
    const row = release.archives.find(archive => archive.role === 'wllama');
    if (!row) throw new Error(`${release.tag} publishes no wllama archive; build werg/wllama on it and pass --wllama DIR`);
    const response = await fetch(`${base}/${row.file}`, { headers });
    if (!response.ok) throw new Error(`${base}/${row.file}: HTTP ${response.status}`);
    const data = Buffer.from(await response.arrayBuffer());
    if (createHash('sha256').update(data).digest('hex') !== row.sha256) throw new Error(`${row.file} does not match its manifest digest`);
    temporary = await mkdtemp(join(tmpdir(), 'natlang-wllama-'));
    await writeFile(join(temporary, row.file), data);
    execFileSync('tar', ['-xzf', join(temporary, row.file), '-C', temporary]);
    built = temporary;
    wllama = row.wllama;
  }
  const files = { 'wllama/esm': 'esm', 'wllama-compat/index.js': 'compat/index.js', 'wllama-compat/wasm/wllama.js': 'compat/wasm/wllama.js',
    'wllama-compat/wasm/wllama.wasm': 'compat/wasm/wllama.wasm' };
  await rm(join(vendor, 'wllama/esm'), { recursive: true, force: true });
  for (const [to, from] of Object.entries(files)) {
    await mkdir(dirname(join(vendor, to)), { recursive: true });
    await cp(join(built, from), join(vendor, to), { recursive: true, filter: source => !/\.(map|md)$/.test(source) && !/index\.(min\.js|cjs)$/.test(source) });
  }
  const sha256 = async path => createHash('sha256').update(await readFile(join(vendor, path))).digest('hex');
  const provenancePath = join(vendor, 'wllama/provenance.json');
  const previous = JSON.parse(await readFile(provenancePath, 'utf8'));
  const provenance = { schema: 'natlang.wllama-vendor/2',
    llama_cpp: { repository, release: release.tag, commit: release.commit },
    wllama,
    build: value('--wllama') ? `local build of ${built} (werg/wllama scripts/build_wasm.sh: emsdk docker, WebGPU JSPI main build and compat build; npm run build)`
      : `${repository} .github/workflows/natlang-runtime.yml job wllama (werg/wllama scripts/build_wasm.sh; npm run build)`,
    sha256: Object.fromEntries(await Promise.all(['wllama/esm/index.js', 'wllama/esm/wasm/wllama.wasm', 'wllama-compat/index.js',
      'wllama-compat/wasm/wllama.js', 'wllama-compat/wasm/wllama.wasm'].map(async path => [path, await sha256(path)]))),
    verify: 'node scripts/wllama_smoke.mjs --model <LFM3 gguf> --server <this release\'s llama-server> (docs/ENGINE_PARITY.md)' };
  await writeFile(provenancePath, JSON.stringify(provenance, null, 1) + '\n');
  for (const name of ['wllama', 'wllama-compat']) {
    const path = join(vendor, name, 'package.json'), pkg = JSON.parse(await readFile(path, 'utf8'));
    pkg.version = pkg.version.replace(/-natlang\..*$/, '') + `-natlang.${release.tag.replace(/^natlang-/, '')}`;
    await writeFile(path, JSON.stringify(pkg, null, 2) + '\n');
  }
  if (temporary) await rm(temporary, { recursive: true, force: true });
}

const stable = await getJson(`https://api.github.com/repos/ggml-org/llama.cpp/releases/tags/v${requested}`);
const pointer = stable.assets.find(asset => asset.name === 'nightly-tag.txt');
if (!pointer) throw new Error(`v${requested} has no signed build pointer`);
const buildTag = await getText(pointer.browser_download_url);
const buildMatch = /^b(\d+)$/.exec(buildTag);
if (!buildMatch) throw new Error(`invalid llama.cpp build tag: ${buildTag}`);
const build = Number(buildMatch[1]);
const [release, commit] = await Promise.all([
  getJson(`https://api.github.com/repos/ggml-org/llama.cpp/releases/tags/${buildTag}`),
  getJson(`https://api.github.com/repos/ggml-org/llama.cpp/commits/${buildTag}`),
]);
const definitions = [
  ['linux-x64-cpu', 'linux', 'x64', 'cpu', 'tar.gz', `llama-${buildTag}-bin-ubuntu-x64.tar.gz`],
  ['linux-arm64-cpu', 'linux', 'arm64', 'cpu', 'tar.gz', `llama-${buildTag}-bin-ubuntu-arm64.tar.gz`],
  ['darwin-arm64-metal', 'darwin', 'arm64', 'metal', 'tar.gz', `llama-${buildTag}-bin-macos-arm64.tar.gz`],
  ['darwin-x64-metal', 'darwin', 'x64', 'metal', 'tar.gz', `llama-${buildTag}-bin-macos-x64.tar.gz`],
  ['win32-x64-cpu', 'win32', 'x64', 'cpu', 'zip', `llama-${buildTag}-bin-win-cpu-x64.zip`],
  ['win32-arm64-cpu', 'win32', 'arm64', 'cpu', 'zip', `llama-${buildTag}-bin-win-cpu-arm64.zip`],
];
const artifacts = definitions.map(([key, platform, arch, backend, archive, name]) => {
  const asset = release.assets.find(candidate => candidate.name === name);
  if (!asset || !/^sha256:[0-9a-f]{64}$/.test(asset.digest ?? ''))
    throw new Error(`${buildTag} is missing a digest-bearing ${name}`);
  return { key, platform, arch, backend, archive, url: asset.browser_download_url,
    bytes: asset.size, sha256: asset.digest.slice('sha256:'.length) };
});
const [major, minor] = requested.split('.').map(Number);
const manifest = { version: requested, build, commit: commit.sha.slice(0, 9),
  compatible: { minimumVersion: requested, maximumVersionExclusive: `${major}.${minor + 1}.0`, minimumBuild: build },
  artifacts };
await writeManifest(manifest);
