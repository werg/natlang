#!/usr/bin/env python3
"""Share installed third-party Node packages without sharing workspace code."""
from __future__ import annotations

import json
import os
import shutil
import sys
import tempfile
from pathlib import Path


def _workspace_packages(root: Path) -> dict[str, Path]:
    manifest = json.loads((root / 'package.json').read_text())
    workspace_patterns = manifest.get('workspaces', [])
    if isinstance(workspace_patterns, dict):
        workspace_patterns = workspace_patterns.get('packages', [])
    if not isinstance(workspace_patterns, list) or not all(isinstance(item, str) for item in workspace_patterns):
        raise ValueError('root package.json has an invalid npm workspaces declaration')
    packages: dict[str, Path] = {}
    for pattern in workspace_patterns:
        for package_json in sorted(root.glob(pattern + '/package.json')):
            package_root = package_json.parent.resolve(strict=True)
            name = json.loads(package_json.read_text()).get('name')
            if not isinstance(name, str) or not name:
                raise ValueError(f'workspace package has no valid name: {package_json}')
            if name in packages:
                raise ValueError(f'duplicate workspace package name: {name}')
            packages[name] = package_root
    return packages


def _workspace_links_are_local(root: Path, packages: dict[str, Path]) -> bool:
    modules = root / 'node_modules'
    for name, package_path in packages.items():
        link = modules.joinpath(*name.split('/'))
        try:
            if link.resolve(strict=True) != package_path:
                return False
        except OSError:
            return False
    return True


def _link(target: Path, link: Path) -> None:
    link.parent.mkdir(parents=True, exist_ok=True)
    link.symlink_to(target, target_is_directory=target.is_dir())


def prepare(root: Path, main: Path) -> bool:
    """Make a linked worktree resolve local workspaces and shared dependencies.

    Returns whether a local dependency overlay was created. Existing local
    installs are preserved; only the exact root-level symlink created by the
    former check-main setup may be replaced.
    """
    root = Path(root).resolve(strict=True)
    main = Path(main).resolve(strict=True)
    if root == main:
        return False
    shared_modules = main / 'node_modules'
    if not shared_modules.is_dir():
        raise FileNotFoundError(f'canonical third-party node_modules is missing: {shared_modules}')
    packages = _workspace_packages(root)
    modules = root / 'node_modules'
    if modules.is_dir() and not modules.is_symlink():
        if not _workspace_links_are_local(root, packages):
            raise ValueError(f'existing worktree node_modules has non-local/incomplete workspace links: {modules}')
        return False
    if modules.is_symlink():
        try:
            linked_root = modules.resolve(strict=True)
        except OSError as error:
            raise ValueError(f'worktree node_modules is a broken symlink: {modules}') from error
        if linked_root != shared_modules.resolve(strict=True):
            raise ValueError(f'refusing to replace unrelated node_modules symlink: {modules} -> {linked_root}')
    elif modules.exists():
        raise ValueError(f'refusing to replace an unknown node_modules path: {modules}')

    temporary = Path(tempfile.mkdtemp(prefix='.check-main-node-modules-', dir=root))
    try:
        workspace_names = set(packages)
        for entry in sorted(shared_modules.iterdir(), key=lambda item: item.name):
            if entry.name.startswith('@') and entry.is_dir():
                scoped = temporary / entry.name
                for package in sorted(entry.iterdir(), key=lambda item: item.name):
                    qualified = f'{entry.name}/{package.name}'
                    if qualified in workspace_names:
                        continue
                    _link(package, scoped / package.name)
                if scoped.exists() and not any(scoped.iterdir()):
                    scoped.rmdir()
            else:
                _link(entry, temporary / entry.name)
        for name, package_path in packages.items():
            _link(package_path, temporary.joinpath(*name.split('/')))

        # Verify every workspace link resolves into the tested checkout before
        # the old exact symlink is replaced.
        for name, package_path in packages.items():
            link = temporary.joinpath(*name.split('/'))
            if link.resolve(strict=True) != package_path:
                raise ValueError(f'worktree workspace link does not resolve locally: {name}')

        if modules.is_symlink():
            previous = root / f'.check-main-node-modules-previous-{os.getpid()}'
            os.replace(modules, previous)
            try:
                os.replace(temporary, modules)
            except BaseException:
                os.replace(previous, modules)
                raise
            previous.unlink()
        else:
            os.replace(temporary, modules)
    finally:
        if temporary.exists():
            shutil.rmtree(temporary)
    return True


def main(argv: list[str] | None = None) -> int:
    values = sys.argv[1:] if argv is None else argv
    if len(values) != 2:
        raise SystemExit('usage: prepare_check_main_node_modules.py WORKTREE_ROOT MAIN_CHECKOUT_ROOT')
    changed = prepare(Path(values[0]), Path(values[1]))
    print('created worktree-local workspace dependency overlay' if changed else 'workspace dependency overlay unchanged')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
